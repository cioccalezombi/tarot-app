export function shuffleDeck(deck: TarotCard[]): TarotCard[] {
  const arr = [...deck];
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
}

export interface DrawnCard {
  card: TarotCard;
  isReversed: boolean;
  position: string;
}

export function drawCards(positions: string[], customDeck?: TarotCard[]): DrawnCard[] {
  const deckToUse = customDeck ? customDeck : shuffleDeck(DECK);
  return positions.map((position, index) => ({
    card: deckToUse[index],
    isReversed: Math.random() < 0.3,
    position,
  }));
}

// ── Funciones de corte y barajado interactivo ──────────────────
export const MIN_CARDS_PER_PILE = 3;

export function cortesValidos(cortes: number[], largo: number, minimo: number = MIN_CARDS_PER_PILE): boolean {
  const p = [0, ...cortes, largo];
  return p.every((v, i) => i === 0 || v - p[i - 1] >= minimo);
}

export function cortesAlAzar(largo: number, n: number, minimo: number = MIN_CARDS_PER_PILE): number[] {
  let c: number[];
  do {
    c = Array.from(
      { length: n - 1 },
      () => minimo + Math.floor(Math.random() * (largo - 2 * minimo + 1))
    ).sort((a, b) => a - b);
  } while (!cortesValidos(c, largo, minimo));
  return c;
}

export function cortarMazo<T>(mazo: T[], cortes: number[]): T[][] {
  const p = [0, ...cortes, mazo.length];
  return p.slice(0, -1).map((ini, i) => mazo.slice(ini, p[i + 1]));
}

export function juntarMontones<T>(montones: T[][], orden: number[]): T[] {
  return orden.flatMap((i) => montones[i]);
}
